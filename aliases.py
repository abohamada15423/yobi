import re

_TRADEMARK_RE = re.compile(r"[®™©]")


def normalize_name(name: str) -> str:
    """Lowercase, strip trademark symbols, collapse whitespace."""
    if not name:
        return ""
    s = name.lower().strip()
    s = _TRADEMARK_RE.sub("", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


